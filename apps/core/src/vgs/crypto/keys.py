"""Loading master keys from the configuration, and checking a backup copy.

The master key is generated by us (``keytool generate``), stored in the password manager as
the offline backup, and given to the running process through its environment (see ADR 0006).
It is never written in the repository, in the database or in the object storage.
"""

from __future__ import annotations

import base64
import binascii
import hashlib
import hmac
import json

from vgs.config import Settings
from vgs.crypto.envelope import KEY_BYTES, KeyProvider, StaticKeyProvider

_FINGERPRINT_LABEL = b"vgs-master-key-fingerprint-v1"


class KeyConfigError(ValueError):
    """The key configuration is missing or malformed (never contains key material)."""


def fingerprint(key_b64: str) -> str:
    """Short check value of a key: lets a person confirm that the copy in the password manager
    is the one in use, without revealing anything useful about the key."""
    key = _decode(key_b64, "key")
    return hmac.new(key, _FINGERPRINT_LABEL, hashlib.sha256).hexdigest()[:8]


def provider_from_settings(settings: Settings) -> KeyProvider:
    if settings.master_key_b64 is None:
        raise KeyConfigError("MASTER_KEY_B64 is not set")
    retired: dict[str, str] = {}
    if settings.master_keys_retired_json is not None:
        try:
            parsed = json.loads(settings.master_keys_retired_json.get_secret_value())
        except json.JSONDecodeError:
            raise KeyConfigError("MASTER_KEYS_RETIRED_JSON is not valid JSON") from None
        if not isinstance(parsed, dict) or not all(
            isinstance(k, str) and isinstance(v, str) for k, v in parsed.items()
        ):
            raise KeyConfigError("MASTER_KEYS_RETIRED_JSON must map key ids to base64 keys")
        retired = parsed
    if settings.master_key_id in retired:
        raise KeyConfigError("the current key id must not also be listed as retired")
    current = (settings.master_key_id, settings.master_key_b64.get_secret_value())
    for name, value in [current, *retired.items()]:
        _decode(value, f"key {name!r}")
    return StaticKeyProvider.from_b64(
        settings.master_key_id, settings.master_key_b64.get_secret_value(), retired
    )


def _decode(value: str, label: str) -> bytes:
    try:
        raw = base64.b64decode(value, validate=True)
    except (binascii.Error, ValueError):
        raise KeyConfigError(f"{label} is not valid base64") from None
    if len(raw) != KEY_BYTES:
        raise KeyConfigError(f"{label} must decode to exactly {KEY_BYTES} bytes")
    return raw
